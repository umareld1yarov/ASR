import 'package:isar_community/isar.dart';

part 'user_profile.g.dart';

/// Локальный профиль пользователя — ровно одна запись (как CurrentActivity).
/// Аватар/имя/миссия — чисто локальные настройки, без авторизации.
@collection
class UserProfile {
  Id id = 0;

  String name = 'Пользователь';

  /// Путь к файлу аватара на диске (та же папка, что и фото записей).
  String? avatarPath;

  /// Личная миссия — одна фраза о том, зачем человек ведёт трекер
  /// (например "Стать тем, кем я хочу быть"). Опционально, до ~60 символов
  /// по UI-конвенции (не ограничено на уровне модели).
  String? missionStatement;
}
